type MenuItemConfig = Omit<
  MenuItemProps,
  "onClick" | "inGroup" | "isLastInGroup"
> & { path?: string };

type ProfileMenuProps = {
  onItemClick?: (label: string) => void;
};

export default function ProfileMenu({ onItemClick }: ProfileMenuProps) {
  const { t, i18n } = useTranslation();
  const navigate = useNavigate();
  const { data: profile, isLoading } = useProfileQuery();
  const telegramUserId = useAuthStore((s) => s.telegramUserId);

  const fullName =
    profile?.name ||
    [profile?.first_name, profile?.last_name].filter(Boolean).join(" ") ||
    (isLoading ? t("common.loading") : t("profileMenu.notSpecified"));

  const refBalance =
    profile?.calculated_balance != null
      ? `$${Math.floor(profile.calculated_balance).toLocaleString("en-US")}`
      : "$0";

  const monthlyTurnover =
    profile?.turnover_30days != null
      ? `$${profile.turnover_30days.toLocaleString("en-US")}`
      : "$0.00";

  const verificationValue =
    profile?.is_verified === true ? (
      <span className="flex items-center gap-1.5">
        <Check className="size-4 text-white/60" />
        {t("profileMenu.verified")}
      </span>
    ) : profile?.is_verified === false ? (
      <span className="flex items-center gap-1.5">
        {t("profileMenu.notVerified")}
      </span>
    ) : (
      <span className="flex items-center gap-1.5 text-white/70">
        {t("profileMenu.unknownVerification")}
      </span>
    );

  const shortTelegramId =
    telegramUserId && telegramUserId.length > 10
      ? `${telegramUserId.slice(0, 6)}...${telegramUserId.slice(-4)}`
      : telegramUserId || "—";

  const languageValue = i18n.language.startsWith("en") ? t("language.en") : t("language.ru");

  const MENU_SECTIONS: { items: MenuItemConfig[]; grouped?: boolean }[] = [
    {
      items: [
        {
          icon: ReferralIcon,
          label: t("profileMenu.referralProgram"),
          value: refBalance,
          sensitive: true,
          path: "/referral",
        },
      ],
    },
    {
      items: [
        {
          icon: TurnoverIcon,
          label: t("profileMenu.turnover30Days"),
          value: monthlyTurnover,
          sensitive: true,
          path: "/turnover",
        },
      ],
    },
    {
      items: [
        { icon: KYCIcon, label: t("profileMenu.fullName"), value: fullName, path: "/kyc" },
        {
          icon: TelegramIcon,
          label: t("profileMenu.telegramId"),
          value: shortTelegramId,
          clickable: false,
        },
        {
          icon: VerifiedIcon,
          label: t("profileMenu.verification"),
          value: verificationValue,
          clickable: false,
        },
      ],
    },
    {
      items: [
        {
          icon: AboutUsIcon,
          label: t("profileMenu.aboutUs"),
          path: "/about",
        },
        { icon: SupportIcon, label: t("profileMenu.support"), value: "@rufin_support", path: "https://t.me/rufin_support" },
        { icon: AddressIcon, label: t("profileMenu.address"), path: "/address" },
        { icon: RulesIcon, label: t("profileMenu.rules"), path: "/rules" },
        { icon: LoyaltyIcon, label: t("profileMenu.loyaltyProgram"), path: "/loyalty" },
      ],
    },
    { items: [{ icon: LanguageIcon, label: t("profileMenu.language"), value: languageValue, path: "/language" }] },
  ];

  return (
    <nav className="flex w-full max-w-md mt-8 flex-col gap-4">
      {MENU_SECTIONS.map((section, i) => {
        const grouped = section.grouped !== false;
        const items = section.items.map((item, j) => (
          <MenuItem
            key={`${String(item.path ?? "item")}-${j}`}
            {...item}
            labelClassName={cn(item.labelClassName, "font-bold")}
            onClick={
              item.clickable !== false
                ? () => {
                  if (item.path) {
                    if (item.path.startsWith("https://t.me/")) {
                      openTelegramLink(item.path);
                    } else if (item.path.startsWith("http")) {
                      window.open(item.path, "_blank");
                    } else {
                      navigate(item.path);
                    }
                  }
                  onItemClick?.(item.label);
                }
                : undefined
            }
            inGroup={grouped}
            isLastInGroup={grouped ? j === section.items.length - 1 : true}
          />
        ));

        return grouped ? (
          <MenuGroup className="rounded-[20px]" key={i}>{items}</MenuGroup>
        ) : (
          <div key={i} className="flex flex-col gap-2">
            {items}
          </div>
        );
      })}
    </nav>
  );
}
